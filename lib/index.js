/**
 * Every non-internal IPv4 address on this machine.
 * @returns `{ name, address }` pairs in interface order.
 */
function ipv4Addresses() {
	const found = [];
	for (const [name, list] of Object.entries(networkInterfaces())) for (const item of list ?? []) {
		if (item.family !== "IPv4" || item.internal) continue;
		found.push({
			name,
			address: item.address
		});
	}
	return found;
}
/** How long the probed default-route address is reused. */
const ROUTE_TTL_MS = 60 * 1e3;
/** Local address the default route leaves from, or null when unknown. */
let routeAddress = null;
/** When routeAddress was probed. */
let routeAddressAt = 0;
/** Whether a probe is already in flight. */
let routeProbe = null;
/**
* Ask the OS which local address the default route uses: a UDP `connect`
* resolves the route without sending a packet or resolving a name, so this
* works the same on macOS, Linux and Windows — no shell parsing.
* @returns the local IPv4 address, or null.
*/
function probeDefaultRouteAddress(timeoutMs = 500) {
	if (routeProbe !== null) return routeProbe;
	const probe = new Promise((resolve) => {
		let settled = false;
		let timer;
		const socket = createSocket("udp4");
		const finish = (value) => {
			if (settled) return;
			settled = true;
			if (timer !== void 0) clearTimeout(timer);
			try {
				socket.close();
			} catch {}
			resolve(value);
		};
		timer = setTimeout(() => finish(null), timeoutMs);
		socket.on("error", () => finish(null));
		try {
			socket.connect(53, "8.8.8.8", () => {
				try {
					const address = socket.address().address;
					finish(typeof address === "string" && address !== "" ? address : null);
				} catch {
					finish(null);
				}
			});
		} catch {
			finish(null);
		}
	}).finally(() => {
		routeProbe = null;
	});
	routeProbe = probe;
	return probe;
}
/**
 * Interface the default route egresses on, when the platform tool is present.
 * @returns interface name, or null.
 */
function defaultRouteInterface() {
	try {
		if (process.platform === "darwin") return execFileSync("route", [
			"-n",
			"get",
			"default"
		], { encoding: "utf8" }).match(/interface:\s*(\S+)/u)?.[1] ?? null;
		if (process.platform === "linux") return execFileSync("ip", [
			"route",
			"show",
			"default"
		], { encoding: "utf8" }).match(/dev\s+(\S+)/u)?.[1] ?? null;
	} catch {}
	return null;
}
